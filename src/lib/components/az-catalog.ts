interface SeedSpec {
  name: string;
  slug?: string;
  category: AzCategory;
  subcategory: string;
  manufacturer: string;
  partNumber: string;
  packageType: string;
  dimensions: string;
  visualShape: VisualShape;
  operatingVoltage: string;
  operatingCurrent: string;
  powerConsumption: string;
  ioDetails: string;
  protocols: string[];
  workingPrinciple?: string;
  internalArchitecture?: string;
  frequencyRange?: string;
  measurementRange?: string;
  accuracy?: string;
  resolution?: string;
  estimatedCostUsd: number | null;
  datasheetUrl: string | null;
  manufacturerUrl: string | null;
  pinout?: AzPinoutItem[];
  alternatives?: string[];
}

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function buildRecord(seed: SeedSpec): AzComponentRecord {
  const slug = seed.slug ?? slugify(seed.name);
  const letter = seed.name.charAt(0).toUpperCase();
  const defaultPins: AzPinoutItem[] = seed.pinout ?? [
    { pin: "1", name: "VCC / IN+", function: `Supply or primary input (${seed.operatingVoltage})`, voltage: seed.operatingVoltage },
    { pin: "2", name: "OUT / SIG", function: `Signal output / interface (${seed.ioDetails})`, voltage: seed.operatingVoltage },
    { pin: "3", name: "GND / REF", function: "Common ground / return reference", voltage: "0 V" },
  ];

  const isMcuOrSensor =
    seed.category === "Microcontrollers" ||
    seed.category === "Sensors" ||
    seed.category === "IoT modules" ||
    seed.category === "Communication modules" ||
    seed.category === "Displays";

  const workingPrinciple =
    seed.workingPrinciple ??
    `${seed.name} operates as a ${seed.subcategory.toLowerCase()} component at ${seed.operatingVoltage} with ${seed.ioDetails}.`;
  const internalArchitecture =
    seed.internalArchitecture ??
    `${seed.packageType} (${seed.dimensions}) package integrating ${seed.protocols.length > 0 ? seed.protocols.join(", ") : "analog/discrete"} signal stages.`;

  return {
    slug,
    letter,
    name: seed.name,
    category: seed.category,
    subcategory: seed.subcategory,
    manufacturer: seed.manufacturer,
    partNumber: seed.partNumber,
    packageType: seed.packageType,
    dimensions: seed.dimensions,
    visualShape: seed.visualShape,
    description: `${seed.name} (${seed.partNumber}) by ${seed.manufacturer}. ${workingPrinciple}`,
    workingPrinciple,
    internalArchitecture,
    operatingVoltage: seed.operatingVoltage,
    operatingCurrent: seed.operatingCurrent,
    powerConsumption: seed.powerConsumption,
    ioDetails: seed.ioDetails,
    protocols: seed.protocols,
    frequencyRange: seed.frequencyRange,
    measurementRange: seed.measurementRange,
    accuracy: seed.accuracy,
    resolution: seed.resolution,
    operatingTemp: "-40°C to +85°C (verify datasheet)",
    compatibleMcus: ["ESP32", "STM32", "Arduino Uno", "Raspberry Pi Pico (RP2040)", "Raspberry Pi 4/5"],
    compatibleModules: ["Logic Level Converter (3.3V/5V)", "100 nF Decoupling MLCC", "ESD TVS Diode"],
    pinout: defaultPins,
    wiringNotes: `Connect ${defaultPins[0]?.name ?? "VCC"} to ${seed.operatingVoltage}, tie GND to common system ground, and verify logic level compatibility (${seed.protocols.join(", ") || seed.ioDetails}).`,
    exampleCircuit: `Power rail with 100 nF ceramic decoupling capacitor close to VCC/GND; signal line routed to MCU ${seed.protocols[0] ?? "GPIO"} pin.`,
    codeExamples: isMcuOrSensor
      ? {
          arduino: `// ${seed.name} (${seed.partNumber}) — Arduino Starter\nvoid setup() {\n  Serial.begin(115200);\n  pinMode(2, INPUT);\n}\nvoid loop() {\n  Serial.println(digitalRead(2));\n  delay(500);\n}`,
          esp32: `// ${seed.name} — ESP32 (Arduino / ESP-IDF)\n#include <Arduino.h>\nvoid setup() { Serial.begin(115200); }\nvoid loop() { Serial.println("${seed.partNumber} active"); delay(1000); }`,
          stm32: `/* ${seed.name} — STM32Cube HAL */\nHAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);\nHAL_Delay(500);`,
          raspberryPi: `# ${seed.name} — Raspberry Pi Python\nimport time\nprint("Polling ${seed.partNumber} on ${seed.protocols[0] ?? "GPIO"}")\ntime.sleep(1)`,
        }
      : {
          arduino: `// ${seed.name} (${seed.partNumber}) is a hardware/passive/power element controlled or monitored via MCU GPIO/ADC.`,
        },
    applications: [
      "Smart Metering & Industrial Telemetry",
      "Embedded IoT Prototypes",
      "Robotics & Laboratory Bench Testing",
    ],
    advantages: [
      `Standard ${seed.packageType} form factor for rapid prototyping and PCB integration`,
      `Well-documented ${seed.protocols.join("/") || seed.ioDetails} interface`,
    ],
    disadvantages: [
      "Verify thermal derating and voltage tolerances against manufacturer datasheet before production",
    ],
    alternatives: seed.alternatives ?? ["Consult Knowledge Base alternatives"],
    datasheetUrl: seed.datasheetUrl,
    manufacturerUrl: seed.manufacturerUrl,
    estimatedCostUsd: seed.estimatedCostUsd,
    supplierInfo: "Estimated reference pricing (DigiKey / Mouser / LCSC) — verify live stock & lead time",
    verificationStatus: "typical",
    images: [
      {
        role: "main",
        title: `${seed.name} — Technical Package Diagram`,
        isIllustrative: true,
        attribution: "My Engineering Lab Procedural SVG",
        license: "CC0 / Internal",
        available: true,
      },
      {
        role: "pinout",
        title: `${seed.name} — Pinout Diagram`,
        isIllustrative: true,
        attribution: "My Engineering Lab Procedural SVG",
        license: "CC0 / Internal",
        available: true,
      },
      {
        role: "circuit",
        title: `${seed.name} — Example Connection Circuit`,
        isIllustrative: true,
        attribution: "My Engineering Lab Procedural SVG",
        license: "CC0 / Internal",
        available: true,
      },
      {
        role: "manufacturer",
        title: `${seed.name} — Official Manufacturer Photograph`,
        isIllustrative: false,
        attribution: seed.manufacturer,
        license: "Manufacturer Documentation",
        storagePath: null,
        available: false,
      },
    ],
  };
}

