export const AZ_LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("");

export function getAzComponentBySlug(slug: string): AzComponentRecord | undefined {
  return AZ_COMPONENTS.find((c) => c.slug === slug);
}

export function getAzCountsByLetter(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const l of AZ_LETTERS) counts[l] = 0;
  for (const c of AZ_COMPONENTS) {
    counts[c.letter] = (counts[c.letter] ?? 0) + 1;
  }
  return counts;
}

