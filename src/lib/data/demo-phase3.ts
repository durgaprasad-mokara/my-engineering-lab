/**
 * Generate 360-degree radiation pattern points for visualizer
 */
function generatePatternData(
  type: "omnidirectional" | "directional" | "hemispherical",
  peakGainDbi: number,
  beamwidthDeg = 45,
): RadiationPatternPoint[] {
  const points: RadiationPatternPoint[] = [];

  for (let deg = 0; deg < 360; deg += 5) {
    const rad = (deg * Math.PI) / 180;
    let eGain = -30;
    let hGain = -30;

    if (type === "omnidirectional") {
      // Dipole/Monopole: H-plane (azimuth) is circular (uniform gain)
      // E-plane (elevation) has donut figure-8 pattern (nulls at 90 and 270 deg)
      hGain = peakGainDbi - 0.5 * Math.sin(rad * 2); // slight ripple in reality
      const sinElev = Math.sin(rad);
      eGain = peakGainDbi + 20 * Math.log10(Math.max(0.01, Math.abs(sinElev)));
      eGain = Math.max(-28, Math.min(peakGainDbi, eGain));
    } else if (type === "directional") {
      // Yagi/Log-periodic: Main forward lobe at 0 deg, front-to-back ratio ~ 18 dB
      const angleFromCenter = Math.min(deg, 360 - deg);
      const halfBw = beamwidthDeg / 2;
      const normalizedAngle = angleFromCenter / halfBw;
      const mainLobe = peakGainDbi - 12 * Math.pow(normalizedAngle, 2);
      const backLobe = peakGainDbi - 18 + 4 * Math.cos(rad);
      hGain = Math.max(backLobe, Math.max(-30, mainLobe));

      const elevAngle = Math.abs(90 - Math.abs(deg - 180));
      eGain = peakGainDbi - 15 * Math.pow(elevAngle / halfBw, 2);
      eGain = Math.max(-28, Math.min(peakGainDbi, eGain));
    } else {
      // Hemispherical (Patch / GNSS): High gain in upper hemisphere (0-180 deg), low/null in back
      const isUpper = deg <= 90 || deg >= 270;
      const theta = (Math.abs(deg > 180 ? 360 - deg : deg) * Math.PI) / 180;
      if (isUpper) {
        hGain = peakGainDbi - 6 * (1 - Math.cos(theta));
        eGain = peakGainDbi * Math.cos(theta);
      } else {
        hGain = -18 - 8 * Math.sin(theta);
        eGain = -22 - 6 * Math.sin(theta);
      }
      hGain = Math.max(-30, Math.min(peakGainDbi, hGain));
      eGain = Math.max(-30, Math.min(peakGainDbi, eGain));
    }

    points.push({
      angle: deg,
      ePlaneDbi: Number(eGain.toFixed(1)),
      hPlaneDbi: Number(hGain.toFixed(1)),
    });
  }

  return points;
}

